CREATE TABLE EL_AREA (
    ID_AREA NUMBER(3) CONSTRAINT PK_EL_AREA PRIMARY KEY,
    NOMBRE_AREA VARCHAR2(40) NOT NULL
);

CREATE TABLE EL_INSTRUCTOR (
    ID_INSTRUCTOR NUMBER(4) CONSTRAINT PK_EL_INSTRUCTOR PRIMARY KEY,
    NOMBRE VARCHAR2(40) NOT NULL,
    APELLIDO VARCHAR2(40) NOT NULL,
    CORREO VARCHAR2(90) NOT NULL,
    TARIFA_HORA NUMBER(9,2) NOT NULL,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL
);

CREATE TABLE EL_TALLER (
    ID_TALLER NUMBER(4) CONSTRAINT PK_EL_TALLER PRIMARY KEY,
    NOMBRE_TALLER VARCHAR2(60) NOT NULL,
    ID_AREA NUMBER(3) NOT NULL,
    ID_INSTRUCTOR NUMBER(4) NOT NULL,
    PRECIO_BASE NUMBER(9,2) NOT NULL,
    DURACION_HORAS NUMBER(3) NOT NULL,
    NIVEL VARCHAR2(12) NOT NULL
);

-- CASO 01. SALA / IDENTITY distinta de la evaluacion institucional
CREATE TABLE EL_SALA (
    ID_SALA NUMBER(4) GENERATED ALWAYS AS IDENTITY
        (START WITH 40 INCREMENT BY 4),
    CODIGO VARCHAR2(12) NOT NULL,
    SEDE VARCHAR2(30) NOT NULL,
    CAPACIDAD NUMBER(3) NOT NULL,
    HABILITADA CHAR(1) DEFAULT 'S' NOT NULL
);

-- CASO 02. PARTICIPANTE
CREATE TABLE EL_PARTICIPANTE (
    ID_PARTICIPANTE NUMBER(4),
    NOMBRE VARCHAR2(40) NOT NULL,
    APELLIDO VARCHAR2(40) NOT NULL,
    CIUDAD VARCHAR2(40) NOT NULL,
    CORREO VARCHAR2(90) NOT NULL,
    TELEFONO VARCHAR2(12),
    FECHA_ALTA DATE DEFAULT SYSDATE NOT NULL
);

-- CASO 03. SESION
CREATE TABLE EL_SESION (
    ID_SESION NUMBER(4),
    ID_TALLER NUMBER(4) NOT NULL,
    ID_SALA NUMBER(4) NOT NULL,
    FECHA_SESION DATE NOT NULL,
    CUPOS NUMBER(3) NOT NULL,
    ESTADO VARCHAR2(12) DEFAULT 'PROGRAMADA' NOT NULL
);

-- CASO 04. INSCRIPCION
CREATE TABLE EL_INSCRIPCION (
    ID_INSCRIPCION NUMBER(5),
    ID_PARTICIPANTE NUMBER(4) NOT NULL,
    ID_SESION NUMBER(4) NOT NULL,
    FECHA_INSCRIPCION DATE DEFAULT SYSDATE NOT NULL,
    DESCUENTO_PCT NUMBER(5,2) DEFAULT 0 NOT NULL,
    SITUACION VARCHAR2(12) DEFAULT 'CONFIRMADA' NOT NULL
);

