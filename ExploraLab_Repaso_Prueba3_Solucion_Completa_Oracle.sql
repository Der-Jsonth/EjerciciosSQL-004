       TO_CHAR(DESCUENTO_PCT,'FM990D00') || '%' AS "Descuento formateado"
FROM EL_INSCRIPCION
WHERE FECHA_INSCRIPCION >= DATE '2026-11-01'
  AND FECHA_INSCRIPCION < DATE '2026-12-01'
ORDER BY FECHA_INSCRIPCION, ID_INSCRIPCION;

-- CASO 20
SELECT S.ID_SESION, T.NOMBRE_TALLER, SA.CODIGO AS "Sala",
       SA.SEDE, TO_CHAR(S.FECHA_SESION,'DD/MM/YYYY') AS "Fecha"
FROM EL_SESION S
JOIN EL_TALLER T ON T.ID_TALLER = S.ID_TALLER
JOIN EL_SALA SA ON SA.ID_SALA = S.ID_SALA
WHERE S.ESTADO = 'PROGRAMADA'
  AND S.FECHA_SESION >= DATE '2026-12-01'
  AND S.FECHA_SESION < DATE '2027-01-01'
  AND SA.HABILITADA = 'S'
ORDER BY S.FECHA_SESION, T.NOMBRE_TALLER;

-- CASO 21
SELECT I.ID_INSCRIPCION, P.NOMBRE || ' ' || P.APELLIDO AS "Participante",
       T.NOMBRE_TALLER AS "Taller", A.NOMBRE_AREA AS "Area",
       T.PRECIO_BASE AS "Precio base", I.DESCUENTO_PCT AS "Descuento %",
       T.PRECIO_BASE * I.DESCUENTO_PCT / 100 AS "Monto descuento",
       T.PRECIO_BASE * (1 - I.DESCUENTO_PCT / 100) AS "Total teorico"
FROM EL_INSCRIPCION I
JOIN EL_PARTICIPANTE P ON P.ID_PARTICIPANTE = I.ID_PARTICIPANTE
JOIN EL_SESION S ON S.ID_SESION = I.ID_SESION
JOIN EL_TALLER T ON T.ID_TALLER = S.ID_TALLER
JOIN EL_AREA A ON A.ID_AREA = T.ID_AREA
WHERE I.SITUACION = 'CONFIRMADA' AND I.DESCUENTO_PCT > 0
ORDER BY "Total teorico" DESC, I.ID_INSCRIPCION;

-- CASO 22
CREATE TABLE EL_PROMOCION_DICIEMBRE AS
SELECT S.ID_SESION, T.NOMBRE_TALLER, SA.CODIGO AS CODIGO_SALA,
       S.FECHA_SESION, T.PRECIO_BASE AS PRECIO_ORIGINAL,
       T.PRECIO_BASE * 0.85 AS PRECIO_PROMOCIONAL
FROM EL_SESION S
JOIN EL_TALLER T ON T.ID_TALLER = S.ID_TALLER
JOIN EL_SALA SA ON SA.ID_SALA = S.ID_SALA
WHERE S.FECHA_SESION >= DATE '2026-12-01'
  AND S.FECHA_SESION < DATE '2027-01-01'
  AND S.ESTADO = 'PROGRAMADA'
  AND T.NIVEL = 'Inicial';

SELECT ID_SESION, NOMBRE_TALLER, PRECIO_ORIGINAL, PRECIO_PROMOCIONAL
FROM EL_PROMOCION_DICIEMBRE
ORDER BY PRECIO_PROMOCIONAL ASC, ID_SESION ASC;

-- CASO 23
-- Para region de grafico de barras en Oracle APEX: Label=NOMBRE_AREA, Value=INSCRITOS
SELECT A.NOMBRE_AREA AS NOMBRE_AREA,
       COUNT(*) AS INSCRITOS
FROM EL_INSCRIPCION I
JOIN EL_SESION S ON S.ID_SESION = I.ID_SESION
JOIN EL_TALLER T ON T.ID_TALLER = S.ID_TALLER
JOIN EL_AREA A ON A.ID_AREA = T.ID_AREA
WHERE I.SITUACION = 'CONFIRMADA'
GROUP BY A.NOMBRE_AREA
ORDER BY INSCRITOS DESC, A.NOMBRE_AREA ASC;

-- CASO 24
-- Para region de grafico de torta en Oracle APEX: Label=SITUACION, Value=CANTIDAD
SELECT SITUACION, COUNT(*) AS CANTIDAD
FROM EL_INSCRIPCION
GROUP BY SITUACION
ORDER BY SITUACION;

-- CASO 25
-- Caso integrador: 7 tablas; condiciones agrupadas, calculos y presentacion
SELECT I.ID_INSCRIPCION AS "N inscripcion",
       P.NOMBRE || ' ' || P.APELLIDO AS "Participante",
       P.CIUDAD AS "Ciudad", A.NOMBRE_AREA AS "Area",
       T.NOMBRE_TALLER AS "Taller",
       N.NOMBRE || ' ' || N.APELLIDO AS "Instructor",
       SA.CODIGO || ' - ' || SA.SEDE AS "Sala y sede",
       TO_CHAR(S.FECHA_SESION,'DD/MM/YYYY') AS "Fecha de sesion",
       TO_CHAR(T.PRECIO_BASE,'FM999G999G990D00') AS "Precio base",
       I.DESCUENTO_PCT AS "Descuento %",
       TO_CHAR(T.PRECIO_BASE * I.DESCUENTO_PCT / 100,
               'FM999G999G990D00') AS "Rebaja",
       TO_CHAR(T.PRECIO_BASE * (1 - I.DESCUENTO_PCT / 100),
               'FM999G999G990D00') AS "Total final"
FROM EL_INSCRIPCION I
JOIN EL_PARTICIPANTE P ON P.ID_PARTICIPANTE = I.ID_PARTICIPANTE
JOIN EL_SESION S ON S.ID_SESION = I.ID_SESION
JOIN EL_TALLER T ON T.ID_TALLER = S.ID_TALLER
JOIN EL_AREA A ON A.ID_AREA = T.ID_AREA
JOIN EL_INSTRUCTOR N ON N.ID_INSTRUCTOR = T.ID_INSTRUCTOR
JOIN EL_SALA SA ON SA.ID_SALA = S.ID_SALA
WHERE I.SITUACION = 'CONFIRMADA'
  AND S.FECHA_SESION >= DATE '2026-11-01'
  AND S.FECHA_SESION < DATE '2027-01-01'
  AND P.CIUDAD <> 'Temuco'
  AND N.ACTIVO = 'S'
  AND I.DESCUENTO_PCT >= 5
  AND (T.NIVEL IN ('Inicial','Intermedio') OR SA.SEDE = 'Sur')
ORDER BY S.FECHA_SESION ASC,
         T.PRECIO_BASE * (1 - I.DESCUENTO_PCT/100) DESC,
         I.ID_INSCRIPCION ASC;
